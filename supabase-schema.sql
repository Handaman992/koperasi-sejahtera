-- Koperasi Sejahtera - akses awal untuk prototype online.
-- Jalankan di Supabase SQL Editor setelah membuat user admin di Authentication.
-- Ganti USER_UUID_DI_SINI dengan UUID user admin dari Authentication > Users.

create table if not exists public.cooperative_memberships (
  id bigint generated by default as identity primary key,
  coop_id text not null,
  user_id uuid not null references auth.users(id) on delete cascade,
  role text not null default 'admin' check (role in ('admin','operator','viewer')),
  created_at timestamptz not null default now(),
  unique (coop_id, user_id)
);

create table if not exists public.cooperative_state (
  coop_id text primary key,
  payload jsonb not null default '{}'::jsonb,
  updated_by uuid references auth.users(id),
  updated_at timestamptz not null default now()
);

alter table public.cooperative_memberships enable row level security;
alter table public.cooperative_state enable row level security;

-- A user may see their own membership only.
drop policy if exists "members can read own membership" on public.cooperative_memberships;
create policy "members can read own membership" on public.cooperative_memberships
for select to authenticated using (user_id = auth.uid());

-- Only a member of the same cooperative can read its state.
drop policy if exists "members can read cooperative state" on public.cooperative_state;
create policy "members can read cooperative state" on public.cooperative_state
for select to authenticated using (
  exists (select 1 from public.cooperative_memberships m
          where m.coop_id = cooperative_state.coop_id and m.user_id = auth.uid())
);

-- Admin and operator may create/update the shared state; viewer is read-only.
drop policy if exists "operators can create cooperative state" on public.cooperative_state;
create policy "operators can create cooperative state" on public.cooperative_state
for insert to authenticated with check (
  updated_by = auth.uid() and exists (
    select 1 from public.cooperative_memberships m
    where m.coop_id = cooperative_state.coop_id and m.user_id = auth.uid()
      and m.role in ('admin','operator')
  )
);
drop policy if exists "operators can update cooperative state" on public.cooperative_state;
create policy "operators can update cooperative state" on public.cooperative_state
for update to authenticated using (
  exists (select 1 from public.cooperative_memberships m
          where m.coop_id = cooperative_state.coop_id and m.user_id = auth.uid()
            and m.role in ('admin','operator'))
) with check (
  updated_by = auth.uid() and exists (
    select 1 from public.cooperative_memberships m
    where m.coop_id = cooperative_state.coop_id and m.user_id = auth.uid()
      and m.role in ('admin','operator')
  )
);

